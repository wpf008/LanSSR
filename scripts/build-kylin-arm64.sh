#!/bin/sh
# Build and package on an ARM64 Linux base with glibc 2.31.
set -eu

usage() {
    cat <<'USAGE'
Usage: sh scripts/build-kylin-arm64.sh [--offline] [--reuse-builder]

--offline        Use only cached Cargo dependencies; no Cargo registry downloads.
--reuse-builder  Reuse an already-built local builder image; skip apt/image build.

Environment overrides:
  LANBRIDGE_BUILDER_IMAGE    Local builder image (default: lanbridge-kylin-arm64-builder)
  LANBRIDGE_BASE_IMAGE       Official Rust ARM64 base image
  LANBRIDGE_HOST_CARGO_HOME  Host Cargo cache (default: CARGO_HOME or ~/.cargo)
  LANBRIDGE_BUILD_JOBS       Parallel Rust build jobs (default: 4)
  LANBRIDGE_VERSION          Debian package version (default: Cargo.toml version)
USAGE
}
cargo_offline=false
reuse_builder=false
while [ "$#" -gt 0 ]; do
    case "$1" in
        --offline) cargo_offline=true ;;
        --reuse-builder) reuse_builder=true ;;
        -h|--help) usage; exit 0 ;;
        *) echo "Unknown argument: $1" >&2; usage >&2; exit 2 ;;
    esac
    shift
done

cd "$(dirname "$0")/.."
project_dir=$(pwd -P)
image_name=${LANBRIDGE_BUILDER_IMAGE:-lanbridge-kylin-arm64-builder}
base_image=${LANBRIDGE_BASE_IMAGE:-public.ecr.aws/docker/library/rust:1.88.0-bullseye}
build_jobs=${LANBRIDGE_BUILD_JOBS:-4}
version=${LANBRIDGE_VERSION:-$(sed -n 's/^version = "\([^"]*\)"/\1/p' Cargo.toml | head -n 1)}
case "$build_jobs" in
    ''|*[!0-9]*) echo "LANBRIDGE_BUILD_JOBS must be a positive integer." >&2; exit 2 ;;
esac
[ "$build_jobs" -gt 0 ] || {
    echo "LANBRIDGE_BUILD_JOBS must be a positive integer." >&2
    exit 2
}
command -v docker >/dev/null 2>&1 || {
    echo "Docker is required; start Docker Desktop or a Linux Docker daemon." >&2
    exit 1
}

# Merge reusable crate archives and sparse-index entries. Cargo extracts source
# archives itself; copying the host's platform-specific build output is avoided.
host_cargo=${LANBRIDGE_HOST_CARGO_HOME:-${CARGO_HOME:-${HOME}/.cargo}}
destination_registry=$project_dir/target/linux-cargo/registry
mkdir -p "$destination_registry"
for component in cache index; do
    source_dir=$host_cargo/registry/$component
    destination_dir=$destination_registry/$component
    if [ -d "$source_dir" ]; then
        mkdir -p "$destination_dir"
        source_dir=$(cd "$source_dir" && pwd -P)
        if [ "$source_dir" != "$(cd "$destination_dir" && pwd -P)" ]; then
            cp -R "$source_dir/." "$destination_dir/"
        fi
    fi
done

if ! "$reuse_builder"; then
    # This local archive is generated by fetch-rust-arm64-image.py with a pinned
    # official manifest and layer hashes. It avoids Docker daemon network issues.
    base_archive=$project_dir/target/build-tools/rust-arm64-image.tar
    if [ "$base_image" = public.ecr.aws/docker/library/rust:1.88.0-bullseye ] &&
        ! docker image inspect "$base_image" >/dev/null 2>&1 && [ -f "$base_archive" ]; then
        docker load --input "$base_archive"
    fi
    # The builder verifies the Debian source archive SHA256 before installing
    # headers. Retain it locally so rebuilding the image can use cached input.
    if [ ! -f packaging/docker/pipewire_0.3.65.orig.tar.bz2 ]; then
        curl --fail --location --proto '=https' --proto-redir '=https' \
            --connect-timeout 15 --retry 3 \
            https://deb.debian.org/debian/pool/main/p/pipewire/pipewire_0.3.65.orig.tar.bz2 \
            --output packaging/docker/pipewire_0.3.65.orig.tar.bz2
    fi
    docker build --platform linux/arm64 -t "$image_name" \
        --build-arg "BASE_IMAGE=$base_image" \
        -f packaging/docker/Dockerfile.bullseye packaging/docker
fi

if [ "$(docker image inspect --format '{{.Architecture}}' "$image_name")" != arm64 ]; then
    echo "The builder image must use the ARM64 architecture." >&2
    exit 1
fi
echo "Building ARM64 package using $image_name (Cargo offline: $cargo_offline)."
docker run --rm --platform linux/arm64 \
    --mount "type=bind,source=$project_dir,target=/workspace" \
    -e CARGO_HOME=/workspace/target/linux-cargo \
    -e CARGO_TARGET_DIR=/workspace/target/linux-arm64 \
    -e "CARGO_BUILD_JOBS=$build_jobs" \
    -e "LANBRIDGE_VERSION=$version" \
    -e "LANBRIDGE_CARGO_OFFLINE=$cargo_offline" \
    "$image_name" sh -eu -c '
        offline_flag=
        if [ "$LANBRIDGE_CARGO_OFFLINE" = true ]; then offline_flag=--offline; fi
        cargo build --locked $offline_flag --release
        cargo test --locked $offline_flag --all-targets
        sh scripts/package-deb.sh target/linux-arm64/release arm64
        sh scripts/verify-deb.sh "dist/linux-arm64/LanSSR_${LANBRIDGE_VERSION}_arm64.deb" \
            --release-directory target/linux-arm64/release
    '
