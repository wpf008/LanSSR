#!/bin/sh
# Build one self-contained Windows 7 SP1 / 10 / 11 x64 distribution.
# Requires cargo-xwin, clang, python3 and matching Rust standard-library
# sources. This script never downloads the standard-library sources.
set -eu
cd "$(dirname "$0")/.."

no_build=0
for option in "$@"; do
    case "$option" in
        --win7) : ;; # Backward-compatible alias for the unified build.
        --no-build) no_build=1 ;;
        -h|--help)
            echo 'Usage: scripts/package-windows.sh [--no-build]'
            echo 'Builds one x64 package for Windows 7 SP1, Windows 10 and Windows 11.'
            exit 0
            ;;
        *)
            echo "Unknown option: $option" >&2
            exit 1
            ;;
    esac
done

# The oldest supported target prevents newer mandatory standard-library
# imports. Optional modern Windows capabilities are resolved at runtime.
target='x86_64-win7-windows-msvc'
platform='windows-x64'
project_dir=$(pwd)
if [ -x target/build-tools/bin/cargo-xwin ]; then
    PATH="$project_dir/target/build-tools/bin:$PATH"
    export PATH
fi

if [ "$no_build" -eq 0 ]; then
    if ! command -v cargo-xwin >/dev/null 2>&1; then
        echo 'Install cargo-xwin first.' >&2
        exit 1
    fi
    # Static MSVC CRT avoids requiring the Visual C++ Redistributable.
    # SDK debug symbols are intentionally omitted; LNK4099 only concerns PDBs.
    XWIN_CACHE_DIR=${XWIN_CACHE_DIR:-"$project_dir/target/xwin-cache"}
    XWIN_ARCH=x86_64
    export XWIN_CACHE_DIR XWIN_ARCH
    rust_version=$(rustc --version | awk '{print $2}')
    rust_library=${LANBRIDGE_RUST_SRC:-"$project_dir/target/build-tools/rust-src-$rust_version/rust-src/lib/rustlib/src/rust/library"}
    if [ -z "${LANBRIDGE_RUST_SRC:-}" ] && [ ! -f "$rust_library/Cargo.toml" ]; then
        rust_library="$(rustc --print sysroot)/lib/rustlib/src/rust/library"
    fi
    if [ ! -f "$rust_library/Cargo.toml" ] || [ ! -f "$rust_library/Cargo.lock" ]; then
        echo "Rust $rust_version standard-library sources are missing at: $rust_library" >&2
        echo 'Set LANBRIDGE_RUST_SRC to the matching Rust library source directory.' >&2
        exit 1
    fi
    rust_library=$(cd "$rust_library" && pwd)
    CARGO_TARGET_X86_64_WIN7_WINDOWS_MSVC_RUSTFLAGS='-C target-feature=+crt-static -C link-arg=/IGNORE:4099 -C link-arg=/SUBSYSTEM:WINDOWS,6.01'
    export CARGO_TARGET_X86_64_WIN7_WINDOWS_MSVC_RUSTFLAGS
    # Cargo 1.98's source override keeps build-std isolated from rustup.
    # Limit these internal/unstable settings to this matching-source build.
    env RUSTC_BOOTSTRAP=1 __CARGO_TESTS_ONLY_SRC_ROOT="$rust_library" \
        cargo xwin build --locked --release -Zbuild-std=std,panic_abort --target "$target" --bins
fi

version=$(python3 -c 'import tomllib; print(tomllib.load(open("Cargo.toml", "rb"))["package"]["version"])')
bundle="dist/LanBridge-${version}-${platform}"
mkdir -p "$bundle"
cp "target/$target/release/LanSender.exe" "$bundle/LanSender.exe"
cp "target/$target/release/LanReceiver.exe" "$bundle/LanReceiver.exe"
# Remove only the configuration previously generated by this packaging script.
rm -f "$bundle/conf/imgBridge.properties"
rmdir "$bundle/conf" 2>/dev/null || true
cp LICENSE "$bundle/LICENSE"
cp vendor/rfd/LICENSE "$bundle/rfd-LICENSE"
cp vendor/egui_glow/LICENSE-MIT "$bundle/egui_glow-LICENSE"
python3 - "$bundle" <<'PY'
from pathlib import Path
import sys
bundle = Path(sys.argv[1])
introduction = '''LanSender / LanReceiver — Windows x64 通用便携版

系统：Windows 7 SP1 / Windows 10 / Windows 11，64 位 Intel / AMD。
同一套 LanSender.exe 和 LanReceiver.exe 自动适配系统可用接口，直接双击运行。
无需 Java、WebView2 或 Visual C++ 运行库安装；界面使用系统窗口及 OpenGL。
界面根据当前图形环境自动选择渲染方式：支持 OpenGL 2.0 及以上时沿用原渲染方式；
Windows 7 仅提供系统 OpenGL 1.1 时使用兼容渲染，不需要额外图形 DLL。
软件渲染速度可能较慢，可在发送端设置页选择 100 毫秒间隔；安装显卡厂商驱动可改善性能。
'''
validation = '本通用包由 macOS 交叉编译生成，已进行 Windows PE 架构、Windows 7 静态导入及打包内容审计，尚未在 Windows 7 / 10 / 11 实机验证，不能保证完全不丢帧。'
text = introduction + '''\
请完整解压 ZIP 后运行，无需配置文件。

使用步骤
1. 双击 LanSender.exe，选择文件。
2. 双击 LanReceiver.exe，在设置页选择接收保存目录（默认系统桌面）。
3. 让接收端能看到发送端的传输画面，点击“开始接收”。定位成功后点击发送端“发送文件”。
4. 接收端可连续接收多份文件；点击历史文件名可在资源管理器中定位文件。
5. 发送端窗口靠左，占所在屏幕工作区约 60% 宽、80% 高；接收端靠右，占约 40% 宽、80% 高。窗口按任务栏和显示缩放调整，必要时缩小控件；接收历史列表独立滚动。
6. 水印默认开启，发送端和接收端的水印开关必须一致。两端均在主界面切换，接收端水印开关位于“开始接收”和“停止接收”之间。
