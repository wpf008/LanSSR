12. 等待提示、传输状态及文件名固定在对应行左侧，当前速度固定在右侧；长文本截断显示。
13. 两端图标采用浅米白底、深绿色细线和叠放方框；右上箭头为发送端，左下箭头为接收端。资源管理器、窗口和任务栏均使用对应图标。
14. LanSender 的“选择文件”使用与麒麟一致的内置文件选择器，跟随应用深浅主题。支持常用位置、磁盘导航、路径输入、当前目录搜索、隐藏文件切换和文件大小及类型查看；输入内容与提示文字垂直居中。单击选择文件，双击进入文件夹或确认文件，底部确认与取消按钮固定，仅文件列表滚动。LanReceiver 设置页仍使用系统目录选择窗口。
15. LanSender 主界面的“全屏 / 退出全屏”按钮或 F11 可切换全屏，Esc 可退出全屏；文件选择器打开时，Esc 先关闭选择器。全屏按当前分辨率和显示缩放扩展传输画面，不切换屏幕分辨率，也不缩放编码格子。传输中切换全屏会重新校准并从头发送，建议发送前切换；实际速率受截图、图像解析和显卡性能限制，不保证一定提速。

程序通过屏幕图像传输文件，不使用局域网连接或 WebView。
''' + validation + '\n'
(bundle / '使用说明.txt').write_text(text.replace('\n', '\r\n'), encoding='utf-8-sig', newline='')
PY
python3 - "$bundle" <<'PY'
from pathlib import Path
import sys
from zipfile import ZIP_DEFLATED, ZipFile
bundle = Path(sys.argv[1])
archive = Path(str(bundle) + '.zip')
# Allowlist program files: never include received documents or unrelated dist files.
files = ['LanSender.exe', 'LanReceiver.exe', 'LICENSE', '使用说明.txt', 'rfd-LICENSE', 'egui_glow-LICENSE']
with ZipFile(archive, 'w', ZIP_DEFLATED, compresslevel=9) as out:
    for name in files:
        out.write(bundle / name, bundle.name + '/' + name)
print(f'Packaged: {bundle}')
print(f'Portable ZIP: {archive}')
PY
# Always audit the common package against the oldest supported system.
python3 scripts/verify-windows.py --version "$version" --target "$target"
